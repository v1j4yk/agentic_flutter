/// Extracting what a package promises, so a change to it is visible.
///
/// # Why a snapshot rather than review
///
/// An API review is a moment; a snapshot is a mechanism. Once a package is
/// published, every removed or renamed export is a breaking change for somebody
/// — and the way those ship is not carelessness but invisibility: a rename in a
/// two-hundred-line diff is one line nobody's eye stops on.
///
/// Writing the surface to a committed file turns that line into a diff in
/// `api/agentic_core.txt`, which is the one place a reviewer is looking for
/// exactly this. The check is not "did you get approval"; it is "did you notice".
///
/// # What it reads, and what it does not
///
/// The barrel files' `export ... show ...` clauses. That is deliberately shallow
/// — it catches a name appearing, disappearing or changing, which is the class
/// of change that breaks a build. It does *not* catch a parameter becoming
/// required or a return type narrowing, which are equally breaking and would
/// need a real element model to see.
///
/// Half a guard rail that costs a hundred lines beats a whole one nobody
/// builds, as long as the half is named. This is that naming.
library;

import 'dart:io';

/// Marks an export whose surface cannot be determined from the barrel.
const String kUnshownMarker = '<unshown export>';

/// The public surface of one package.
final class ApiSurface {
  /// Records a surface.
  ApiSurface({required this.package, required Iterable<String> names})
    : names = List<String>.unmodifiable(names.toSet().toList()..sort());

  /// Reads the surface from a package's barrel file.
  ///
  /// Returns an empty surface when the barrel does not exist, which is what a
  /// package with no public library looks like.
  factory ApiSurface.fromBarrel(String package, String barrelPath) {
    final file = File(barrelPath);
    if (!file.existsSync()) {
      return ApiSurface(package: package, names: const <String>[]);
    }
    return ApiSurface(
      package: package,
      names: parseShownNames(file.readAsStringSync()),
    );
  }

  /// Which package.
  final String package;

  /// Every exported name, sorted.
  final List<String> names;

  /// How many names the package exports.
  int get size => names.length;

  /// Renders the surface as the committed snapshot format.
  ///
  /// One name per line, sorted, with a header that survives a diff without
  /// adding noise. The count is in the header on purpose: a reviewer who sees
  /// `142 names` become `141` knows to look for a removal before reading a
  /// single line of the body.
  String render() => <String>[
    '# $package — public API surface',
    '#',
    '# Generated by `dart run agentic_benchmark:api_snapshot`. Do not edit.',
    '# A diff here is an API change; that is the entire point of the file.',
    '#',
    '# ${names.length} names',
    '',
    ...names,
    '',
  ].join('\n');

  /// Reads a rendered snapshot back.
  static ApiSurface parse(String package, String rendered) => ApiSurface(
    package: package,
    names: <String>[
      for (final line in rendered.split('\n'))
        if (line.trim().isNotEmpty && !line.startsWith('#')) line.trim(),
    ],
  );

  /// Extracts the names in every `export ... show ...` clause of [source].
  ///
  /// An export with no `show` is reported rather than silently ignored: it
  /// re-exports whatever the target library happens to contain, so the surface
  /// cannot be known from the barrel alone and the snapshot would quietly stop
  /// meaning anything.
  static List<String> parseShownNames(String source) {
    final names = <String>[];
    final exports = RegExp(r"export\s+'([^']+)'\s*([^;]*);", multiLine: true);

    for (final match in exports.allMatches(source)) {
      final clause = match.group(2) ?? '';
      final show = RegExp(r'show\s+([^;]+)').firstMatch(clause);
      final target = match.group(1)!;
      if (show == null) {
        final reexported = RegExp(
          r'^package:(agentic_[a-z_]+)/',
        ).firstMatch(target);
        names.add(
          reexported == null
              ? '$kUnshownMarker $target'
              : 're-exports ${reexported.group(1)}',
        );
        continue;
      }
      // `show A hide B` is legal, and the capture runs to the semicolon — so
      // without this the hidden names would be recorded as exported, which is
      // exactly backwards.
      final shown = show.group(1)!.split(RegExp(r'\bhide\b')).first;
      for (final name in shown.split(',')) {
        final trimmed = name.trim();
        if (trimmed.isNotEmpty) names.add(trimmed);
      }
    }
    return names;
  }

  @override
  String toString() => 'ApiSurface($package, $size names)';
}

/// What changed between two surfaces.
final class ApiDiff {
  /// Compares [before] and [after].
  ApiDiff({required this.package, required this.before, required this.after})
    : added = List<String>.unmodifiable(
        after.names.where((n) => !before.names.contains(n)).toList()..sort(),
      ),
      removed = List<String>.unmodifiable(
        before.names.where((n) => !after.names.contains(n)).toList()..sort(),
      );

  /// Which package.
  final String package;

  /// The recorded surface.
  final ApiSurface before;

  /// The current surface.
  final ApiSurface after;

  /// Names that appeared.
  final List<String> added;

  /// Names that vanished.
  ///
  /// The half that matters after 1.0: an addition is a minor version, a removal
  /// is a major one and somebody's build.
  final List<String> removed;

  /// Whether anything changed.
  bool get hasChanges => added.isNotEmpty || removed.isNotEmpty;

  /// Whether the change would break a caller.
  bool get isBreaking => removed.isNotEmpty;

  /// Renders the change for a terminal.
  String render() {
    if (!hasChanges) return '$package: unchanged (${after.size} names)';
    final buffer = StringBuffer('$package:');
    for (final name in removed) {
      buffer.write('\n  - $name');
    }
    for (final name in added) {
      buffer.write('\n  + $name');
    }
    if (isBreaking) {
      buffer.write(
        '\n  ${removed.length} removal(s) — breaking for anyone who used them.',
      );
    }
    return buffer.toString();
  }

  @override
  String toString() => 'ApiDiff($package, +${added.length} -${removed.length})';
}

