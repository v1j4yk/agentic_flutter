/// The public API at the level of signatures, not just names.
///
/// `api_surface.dart` records which names a package exports. That catches a
/// class disappearing, but not the changes that break callers more often: a
/// parameter becoming required, a return type narrowing, a constructor
/// vanishing, a `final` class that used to be extendable. This reads the
/// resolved element model and writes one line per declaration:
///
/// ```text
/// ToolExecutor: final class ToolExecutor implements Disposable
/// ToolExecutor.new: ToolExecutor({required ToolSet tools, ...})
/// ToolExecutor.execute: Future<ToolResult> execute(ToolCallPart call, ...)
/// ```
///
/// The part before the colon is a stable key, so a diff can tell a *changed*
/// declaration from a removed one.
library;

import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/type.dart';

/// One package's declarations, keyed by `Owner.member`.
final class ApiSignatures {
  /// Records signatures.
  ApiSignatures({required this.package, required Map<String, String> lines})
    : lines = Map<String, String>.unmodifiable(
        Map<String, String>.fromEntries(
          lines.entries.toList()..sort((a, b) => a.key.compareTo(b.key)),
        ),
      );

  /// Reads a rendered snapshot back.
  factory ApiSignatures.parse(String package, String rendered) {
    final lines = <String, String>{};
    for (final line in rendered.split('\n')) {
      if (line.trim().isEmpty || line.startsWith('#')) continue;
      final colon = line.indexOf(': ');
      if (colon < 0) continue;
      lines[line.substring(0, colon)] = line.substring(colon + 2);
    }
    return ApiSignatures(package: package, lines: lines);
  }

  /// Which package.
  final String package;

  /// Declaration key to signature, sorted by key.
  final Map<String, String> lines;

  /// Renders the committed snapshot format.
  String render() => <String>[
    '# $package — public API signatures',
    '#',
    '# Generated by `dart run agentic_benchmark:api_snapshot`. Do not edit.',
    '# One line per public declaration. A changed line is a changed contract.',
    '#',
    '# ${lines.length} declarations',
    '',
    for (final entry in lines.entries) '${entry.key}: ${entry.value}',
    '',
  ].join('\n');
}

/// What changed between two signature snapshots.
final class SignatureDiff {
  /// Compares [before] and [after].
  SignatureDiff({required this.before, required this.after})
    : added = <String>[
        for (final key in after.lines.keys)
          if (!before.lines.containsKey(key)) key,
      ],
      removed = <String>[
        for (final key in before.lines.keys)
          if (!after.lines.containsKey(key)) key,
      ],
      changed = <String>[
        for (final key in after.lines.keys)
          if (before.lines.containsKey(key) &&
              before.lines[key] != after.lines[key])
            key,
      ];

  /// The recorded signatures.
  final ApiSignatures before;

  /// The current signatures.
  final ApiSignatures after;

  /// Declarations that appeared.
  final List<String> added;

  /// Declarations that vanished.
  final List<String> removed;

  /// Declarations whose signature differs.
  ///
  /// Not every change breaks a caller — a new optional parameter does not —
  /// but every breaking change to an existing declaration lands here, so a
  /// reviewer reads this list line by line.
  final List<String> changed;

  /// Whether anything changed.
  bool get hasChanges =>
      added.isNotEmpty || removed.isNotEmpty || changed.isNotEmpty;

  /// Renders the change for a terminal.
  String render() {
    final package = after.package;
    if (!hasChanges) {
      return '$package: signatures unchanged (${after.lines.length})';
    }
    final buffer = StringBuffer('$package signatures:');
    for (final key in removed) {
      buffer.write('\n  - $key: ${before.lines[key]}');
    }
    for (final key in changed) {
      buffer
        ..write('\n  ~ $key')
        ..write('\n      was: ${before.lines[key]}')
        ..write('\n      now: ${after.lines[key]}');
    }
    for (final key in added) {
      buffer.write('\n  + $key: ${after.lines[key]}');
    }
    return buffer.toString();
  }
}

/// Reads the signatures of every package in [barrels] (package name to
/// barrel path) with one analysis session per package root.
Future<Map<String, ApiSignatures>> readSignatures(
  Map<String, String> barrels,
) async {
  // The analyzer accepts only absolute, normalised paths.
  final paths = <String, String>{
    for (final entry in barrels.entries)
      entry.key: File(entry.value).absolute.uri.normalizePath().toFilePath(),
  };
  final collection = AnalysisContextCollection(
    includedPaths: paths.values.toList(),
  );
  final result = <String, ApiSignatures>{};
  for (final entry in paths.entries) {
    final context = collection.contextFor(entry.value);
    final library = await context.currentSession.getResolvedLibrary(
      entry.value,
    );
    if (library is! ResolvedLibraryResult) {
      throw StateError('Could not resolve ${entry.value}: $library');
    }
    result[entry.key] = ApiSignatures(
      package: entry.key,
      lines: signaturesOfLibrary(library.element, package: entry.key),
    );
  }
  return result;
}

/// Every public declaration exported by [library], keyed by `Owner.member`.
///
/// Only declarations made in [package] are included. An umbrella package that
/// re-exports its siblings would otherwise repeat their whole surface, and
/// every change would be reported twice; the re-export itself is already in
/// the name snapshot.
Map<String, String> signaturesOfLibrary(
  LibraryElement library, {
  required String package,
}) {
  final lines = <String, String>{};
  final exported = library.exportNamespace.definedNames2;
  for (final name in exported.keys) {
    final element = exported[name]!;
    final source = element.library?.uri;
    if (source == null ||
        source.scheme != 'package' ||
        source.pathSegments.first != package) {
      continue;
    }
    switch (element) {
      case InterfaceElement():
        _interface(lines, name, element);
      case ExtensionElement():
        lines[name] =
            'extension $name${_typeParameters(element.typeParameters)} '
            'on ${_type(element.extendedType)}';
        _members(lines, name, element);
      case TopLevelFunctionElement():
        lines[name] = _executable(element, name);
      case TypeAliasElement():
        lines[name] =
            'typedef $name${_typeParameters(element.typeParameters)} = '
            '${_type(element.aliasedType)}';
      case GetterElement():
        final variable = element.variable;
        if (variable is TopLevelVariableElement &&
            !variable.isOriginGetterSetter) {
          lines[name] = _variable(variable, name);
        } else {
          lines[name] = '${_type(element.returnType)} get $name';
        }
      case SetterElement():
        // A setter paired with an exported variable is part of that line.
        if (exported.containsKey(name.replaceAll('=', ''))) continue;
        lines[name] = 'set $name(${_parameters(element.formalParameters)})';
      default:
        lines[name] = element.displayName;
    }
  }
  return lines;
}

void _interface(
  Map<String, String> lines,
  String name,
  InterfaceElement element,
) {
  final header = StringBuffer();
  switch (element) {
    case EnumElement():
      header.write('enum $name');
      lines['$name.values'] = element.constants
          .where((c) => c.isPublic)
          .map((c) => c.name)
          .join(', ');
    case MixinElement():
      header
        ..write(element.isBase ? 'base mixin ' : 'mixin ')
        ..write(name);
      if (element.superclassConstraints.isNotEmpty) {
        header.write(
          ' on ${element.superclassConstraints.map(_type).join(', ')}',
        );
      }
    case ExtensionTypeElement():
      header.write(
        'extension type $name(${_type(element.representation.type)})',
      );
    case ClassElement():
      final modifiers = <String>[
        if (element.isSealed) 'sealed',
        if (element.isAbstract && !element.isSealed) 'abstract',
        if (element.isBase) 'base',
        if (element.isInterface) 'interface',
        if (element.isFinal) 'final',
        if (element.isMixinClass) 'mixin',
        'class',
        name,
      ];
      header.write(modifiers.join(' '));
    default:
      header.write(name);
  }
  header.write(_typeParameters(element.typeParameters));
  if (element is! EnumElement && element is! MixinElement) {
    final supertype = element.supertype;
    if (supertype != null && !supertype.isDartCoreObject) {
      header.write(' extends ${_type(supertype)}');
    }
  }
  if (element.mixins.isNotEmpty) {
    header.write(' with ${element.mixins.map(_type).join(', ')}');
  }
  final interfaces = element.interfaces
      .where((t) => element is! EnumElement || t.element.name != 'Enum')
      .toList();
  if (interfaces.isNotEmpty) {
    header.write(' implements ${interfaces.map(_type).join(', ')}');
  }
  lines[name] = header.toString();

  if (element is! EnumElement) {
    for (final constructor in element.constructors) {
      if (!constructor.isPublic) continue;
      // Abstract, sealed and interface-only classes have an implicit
      // constructor nobody can call from outside; recording it is noise.
      if (constructor.isOriginDeclaration == false &&
          element is ClassElement &&
          (element.isAbstract || element.isSealed)) {
        continue;
      }
      final constructorName = constructor.name ?? 'new';
      final callable = constructorName == 'new'
          ? name
          : '$name.$constructorName';
      lines['$name.$constructorName'] = <String>[
        if (constructor.isConst) 'const',
        if (constructor.isFactory) 'factory',
        '$callable(${_parameters(constructor.formalParameters)})',
      ].join(' ');
    }
  }
  _members(lines, name, element);
}

void _members(
  Map<String, String> lines,
  String owner,
  InstanceElement element,
) {
  for (final field in element.fields) {
    if (!field.isPublic || !field.isOriginDeclaration) continue;
    if (element is EnumElement && field.isEnumConstant) continue;
    if (element is EnumElement && field.name == 'values') continue;
    lines['$owner.${field.name}'] = <String>[
      if (field.isStatic) 'static',
      if (field.isConst)
        'const'
      else if (field.isFinal)
        'final'
      else if (field.isLate)
        'late',
      _type(field.type),
      field.name!,
    ].join(' ');
  }
  for (final getter in element.getters) {
    if (!getter.isPublic || !getter.isOriginDeclaration) continue;
    if (_objectMembers.contains(getter.name)) continue;
    lines['$owner.${getter.name}'] = <String>[
      if (getter.isStatic) 'static',
      '${_type(getter.returnType)} get ${getter.name}',
    ].join(' ');
  }
  for (final setter in element.setters) {
    if (!setter.isPublic || !setter.isOriginDeclaration) continue;
    lines['$owner.${setter.name}='] = <String>[
      if (setter.isStatic) 'static',
      'set ${setter.name}(${_parameters(setter.formalParameters)})',
    ].join(' ');
  }
  for (final method in element.methods) {
    if (!method.isPublic || _objectMembers.contains(method.name)) continue;
    final key = method.isOperator
        ? '$owner.operator${method.name}'
        : '$owner.${method.name}';
    lines[key] = <String>[
      if (method.isStatic) 'static',
      if (method.isAbstract) 'abstract',
      _executable(
        method,
        method.isOperator ? 'operator ${method.name}' : method.name!,
      ),
    ].join(' ');
  }
}

String _executable(ExecutableElement element, String name) =>
    '${_type(element.returnType)} $name'
    '${_typeParameters(element.typeParameters)}'
    '(${_parameters(element.formalParameters)})';

String _variable(TopLevelVariableElement variable, String name) => <String>[
  if (variable.isConst)
    'const'
  else if (variable.isFinal)
    'final'
  else if (variable.isLate)
    'late',
  _type(variable.type),
  name,
].join(' ');

String _parameters(List<FormalParameterElement> parameters) {
  final positional = <String>[];
  final optional = <String>[];
  final named = <String>[];
  for (final p in parameters) {
    final text = StringBuffer()
      ..write(p.isRequiredNamed ? 'required ' : '')
      ..write('${_type(p.type)} ${p.name}');
    if (p.defaultValueCode case final value?) text.write(' = $value');
    if (p.isNamed) {
      named.add('$text');
    } else if (p.isOptionalPositional) {
      optional.add('$text');
    } else {
      positional.add('$text');
    }
  }
  return <String>[
    ...positional,
    if (optional.isNotEmpty) '[${optional.join(', ')}]',
    if (named.isNotEmpty) '{${named.join(', ')}}',
  ].join(', ');
}

String _typeParameters(List<TypeParameterElement> parameters) {
  if (parameters.isEmpty) return '';
  return '<${parameters.map((p) {
    final bound = p.bound;
    return bound == null ? p.name! : '${p.name} extends ${_type(bound)}';
  }).join(', ')}>';
}

String _type(DartType type) => type.getDisplayString();

/// Overrides of `Object` members: every class may declare them, and changing
/// one never breaks a caller's build.
const Set<String> _objectMembers = <String>{
  'toString',
  'hashCode',
  '==',
  'noSuchMethod',
  'runtimeType',
};
